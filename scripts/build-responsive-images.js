/**
 * Derive responsive AVIF/WebP variants for the ASCII art in `public/ascii`.
 *
 * The originals stay in place as the `src` fallback; variants land in
 * `public/ascii/r/` and are described by the generated manifest that
 * `<AsciiImage>` reads, so intrinsic width/height are always available and the
 * hero can never shift layout.
 *
 * Run: npm run build:images
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const root = path.join(__dirname, '..');
const asciiDir = path.join(root, 'public', 'ascii');
const outDir = path.join(asciiDir, 'r');
const manifestFile = path.join(root, 'src', 'lib', 'ascii-images.ts');

/** Widths per art role — chosen from how each is actually laid out. */
const PROFILES = [
  { test: /[\\/]glyphs[\\/]/, widths: [128, 256, 512] },
  { test: /footer-stele/, widths: [960, 1440, 1920] },
  { test: /[\\/]side-/, widths: [320, 512, 768, 1024] },
  { test: /[\\/](hero|page)-/, widths: [640, 960, 1280, 1536] },
];

const AVIF = { quality: 48, effort: 6 };
const WEBP = { quality: 76, effort: 5 };

function widthsFor(file) {
  const hit = PROFILES.find((p) => p.test.test(file));
  return hit ? hit.widths : [640, 1280];
}

function walk(dir, list = []) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) {
      if (path.resolve(full) === path.resolve(outDir)) continue;
      walk(full, list);
    } else if (/\.webp$/i.test(name)) {
      list.push(full);
    }
  }
  return list;
}

function publicPath(file) {
  return '/' + path.relative(path.join(root, 'public'), file).split(path.sep).join('/');
}

async function main() {
  const sources = walk(asciiDir).sort();
  const manifest = {};
  let originalBytes = 0;
  let variantBytes = 0;

  for (const src of sources) {
    const meta = await sharp(src).metadata();
    const rel = path.relative(asciiDir, src).replace(/\.webp$/i, '');
    const targetWidths = widthsFor(src).filter((w) => w <= meta.width);
    if (targetWidths.length === 0) targetWidths.push(meta.width);

    originalBytes += fs.statSync(src).size;

    for (const width of targetWidths) {
      const base = path.join(outDir, `${rel}-${width}`);
      fs.mkdirSync(path.dirname(base), { recursive: true });

      const resized = () => sharp(src).resize({ width, withoutEnlargement: true });
      await resized().avif(AVIF).toFile(`${base}.avif`);
      await resized().webp(WEBP).toFile(`${base}.webp`);

      variantBytes += fs.statSync(`${base}.avif`).size;
    }

    manifest[publicPath(src)] = {
      width: meta.width,
      height: meta.height,
      widths: targetWidths,
    };

    console.log(
      `${publicPath(src).padEnd(44)} ${meta.width}x${meta.height} → ${targetWidths.join(', ')}`
    );
  }

  const body =
    `/**\n` +
    ` * GENERATED by scripts/build-responsive-images.js — do not edit.\n` +
    ` *\n` +
    ` * Intrinsic size and available variant widths for every ASCII art file.\n` +
    ` */\n\n` +
    `export interface AsciiImageMeta {\n` +
    `  width: number;\n` +
    `  height: number;\n` +
    `  widths: number[];\n` +
    `}\n\n` +
    `export const ASCII_IMAGES: Record<string, AsciiImageMeta> = ${JSON.stringify(
      manifest,
      null,
      2
    )};\n`;

  fs.mkdirSync(path.dirname(manifestFile), { recursive: true });
  fs.writeFileSync(manifestFile, body);

  console.log(
    `\n${sources.length} sources · originals ${(originalBytes / 1024 / 1024).toFixed(2)}MB ` +
      `· AVIF variants ${(variantBytes / 1024 / 1024).toFixed(2)}MB`
  );
  console.log(`manifest → ${path.relative(root, manifestFile)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
